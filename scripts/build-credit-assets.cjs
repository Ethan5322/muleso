/* Turns the rendered credit lockups into an importable TS module.
 *
 * jsPDF's addImage needs the bytes in hand. The PDF generators run both in the
 * browser and in API routes, so a fetch() from /public would work in neither
 * reliably — the data URI is inlined instead.
 *
 * Run after scripts/make-agency-credit.cjs.
 * Out: lib/brand/creditAssets.ts
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(process.cwd(), 'public', 'brand');
const OUT = path.join(process.cwd(), 'lib', 'brand', 'creditAssets.ts');

const read = (f) => {
  const p = path.join(SRC, f);
  if (!fs.existsSync(p)) {
    console.error(`Missing ${p}. Run: node scripts/make-agency-credit.cjs`);
    process.exit(1);
  }
  return `data:image/png;base64,${fs.readFileSync(p).toString('base64')}`;
};

const dark = read('mulesoo-credit-on-dark.png');
const light = read('mulesoo-credit-on-light.png');
const compactDark = read('mulesoo-credit-compact-on-dark.png');
const compactLight = read('mulesoo-credit-compact-on-light.png');
const stampDark = read('mulesoo-credit-stamp-on-dark.png');
const stampLight = read('mulesoo-credit-stamp-on-light.png');

fs.writeFileSync(
  OUT,
  `/* GENERATED by scripts/build-credit-assets.cjs — do not edit by hand.
 * Source: public/brand/mulesoo-credit-*.png
 * Regenerate: node scripts/make-agency-credit.cjs && node scripts/build-credit-assets.cjs
 */

/** Stacked lockup, light ink — for dark pages. Transparent PNG. Aspect 4.25. */
export const CREDIT_ON_DARK_PNG =
  '${dark}';

/** Stacked lockup, dark ink — for light pages. Transparent PNG. Aspect 4.25. */
export const CREDIT_ON_LIGHT_PNG =
  '${light}';

/** One-line lockup, light ink — for the ~5mm footer of an ID card. Aspect 11.92. */
export const CREDIT_COMPACT_ON_DARK_PNG =
  '${compactDark}';

/** One-line lockup, dark ink — for a light ID card footer. Aspect 11.92. */
export const CREDIT_COMPACT_ON_LIGHT_PNG =
  '${compactLight}';

/** Stacked lockup + scan-me QR to mulesoo.com, light ink. Aspect 5.58. Print ≥60mm wide. */
export const CREDIT_STAMP_ON_DARK_PNG =
  '${stampDark}';

/** Stacked lockup + scan-me QR to mulesoo.com, dark ink. Aspect 5.58. Print ≥60mm wide. */
export const CREDIT_STAMP_ON_LIGHT_PNG =
  '${stampLight}';
`
);

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0);
console.log(
  `  lib/brand/creditAssets.ts  (stacked ${kb(dark)}/${kb(light)}KB, compact ${kb(compactDark)}/${kb(compactLight)}KB)`
);
